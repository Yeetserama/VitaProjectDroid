#!/bin/sh
# Regenerate or verify the first-boot kit manifest.
#
# The kit manifest covers exactly the payload files that ship in the kit
# directory.  It deliberately does not list build intermediates such as
# initramfs.cpio: that file is embedded in zImage and is not copied to the
# Vita.  scripts/apply-kernel.sh writes a different SHA256SUMS in build/out
# that does include initramfs.cpio.
#
# Usage:
#   scripts/kit-manifest.sh [KIT_DIR] [--check|--print]
#
# Defaults:
#   KIT_DIR = build/first-boot-kit
#   mode    = write SHA256SUMS and verify it
#
# --check  verify the existing SHA256SUMS without rewriting it
# --print  write the manifest to stdout and change nothing

set -eu

REPO_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
KIT_DIR="$REPO_ROOT/build/first-boot-kit"
MODE=write

usage() {
    sed -n '2,21p' "$0" | sed 's/^# \{0,1\}//'
}

for arg in "$@"; do
    case "$arg" in
        --check) MODE=check ;;
        --print) MODE=print ;;
        -h|--help) usage; exit 0 ;;
        -*) echo "kit-manifest: unknown option: $arg" >&2; exit 2 ;;
        *) KIT_DIR=$arg ;;
    esac
done

PAYLOAD="zImage
vita.dtb
vita1000.dtb
vita-selinux-disabled.dtb
system.img
userdata.img
wpa_supplicant.conf.example"

if [ ! -d "$KIT_DIR" ]; then
    echo "kit-manifest: no such directory: $KIT_DIR" >&2
    exit 1
fi

cd "$KIT_DIR"

missing=0
for f in $PAYLOAD; do
    if [ ! -f "$f" ]; then
        echo "kit-manifest: missing payload file: $KIT_DIR/$f" >&2
        missing=1
    fi
done
[ "$missing" -eq 0 ] || exit 1

emit() {
    echo "# AndroidOnVita first-boot kit manifest."
    echo "# Payload files only; initramfs.cpio is embedded in zImage and is not"
    echo "# shipped.  See README.txt for the initramfs reference hash."
    echo "# Generated by scripts/kit-manifest.sh."
    for f in $PAYLOAD; do
        sha256sum "$f"
    done
}

case "$MODE" in
    print)
        emit
        ;;
    write)
        tmp="$KIT_DIR/.SHA256SUMS.$$"
        trap 'rm -f "$tmp"' EXIT HUP INT TERM
        emit > "$tmp"
        mv "$tmp" "$KIT_DIR/SHA256SUMS"
        trap - EXIT HUP INT TERM
        echo "kit-manifest: wrote $KIT_DIR/SHA256SUMS"
        sha256sum -c "$KIT_DIR/SHA256SUMS"
        ;;
    check)
        if [ ! -f "$KIT_DIR/SHA256SUMS" ]; then
            echo "kit-manifest: no SHA256SUMS to check in $KIT_DIR" >&2
            exit 1
        fi
        sha256sum -c "$KIT_DIR/SHA256SUMS"
        # Catch a manifest that verifies but lists the wrong set of files.
        listed=$(sed -e '/^[[:space:]]*#/d' \
                      -e 's/^[0-9a-fA-F]\{64\}[[:space:]]*\*\{0,1\}[[:space:]]*//' \
                      "$KIT_DIR/SHA256SUMS" | sort)
        expected=$(for f in $PAYLOAD; do echo "$f"; done | sort)
        if [ "$listed" != "$expected" ]; then
            echo "kit-manifest: SHA256SUMS lists the wrong file set" >&2
            echo "--- expected ---" >&2
            echo "$expected" >&2
            echo "--- found ---" >&2
            echo "$listed" >&2
            exit 1
        fi
        echo "kit-manifest: file set OK"
        ;;
esac
